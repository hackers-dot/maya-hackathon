# --- TLS expiry / protocol ---

OPENSSL = shutil.which("openssl")
needs_openssl = pytest.mark.skipif(OPENSSL is None, reason="openssl command line not installed")


def make_cert(tmp_path, days: int):
    key, cert = tmp_path / f"k{days}.pem", tmp_path / f"c{days}.pem"
    subprocess.run([OPENSSL, "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes",
                    "-keyout", str(key), "-out", str(cert), "-days", str(days), "-subj", "/CN=maya-test"],
                   check=True, capture_output=True)
    return cert, key


def tls_server(cert, key, max_version=None):
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(cert, key)
    if max_version:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", DeprecationWarning)
            ctx.minimum_version = ssl.TLSVersion.TLSv1
            ctx.maximum_version = max_version
        ctx.set_ciphers("DEFAULT:@SECLEVEL=0")
    srv = socket.socket()
    srv.bind(("127.0.0.1", 0))
    srv.listen()

    def serve():
        try:
            conn, _ = srv.accept()
            with ctx.wrap_socket(conn, server_side=True) as s:
                s.recv(1)
        except OSError:
            pass  # the client closes right after the handshake
    threading.Thread(target=serve, daemon=True).start()
    return srv


@needs_openssl
@pytest.mark.parametrize("days,expected", [(10, ["cert_expires_within_14_days"]),
                                           (20, ["cert_expires_within_30_days"]), (90, [])])
def test_tls_expiry_against_local_server(tmp_path, days, expected):
    srv = tls_server(*make_cert(tmp_path, days))
    try:
        info = fetch_tls("127.0.0.1", frozenset(), port=srv.getsockname()[1])
    finally:
        srv.close()
    assert info["protocol"] in ("TLSv1.2", "TLSv1.3") and info["issuer"] == "CN=maya-test"
    left = datetime.fromisoformat(info["not_after"]) - datetime.now(timezone.utc)
    assert timedelta(days=days - 1) < left <= timedelta(days=days)
    found = tls_findings(info)
    assert [f.check for f in found] == expected
    for f in found:
        assert f.severity == TABLE[f.check].severity == {"cert_expires_within_14_days": "high"}.get(f.check, "medium")
        assert f"not_after={info['not_after']}" in f.evidence[0].data and "issuer=CN=maya-test" in f.evidence[0].data


