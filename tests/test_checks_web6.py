# --- SPF / DMARC over (faked) DNS-over-HTTPS ---

def fake_doh(records: dict, calls: list, status=200):
    def handler(req: httpx.Request):
        calls.append(req)
        if status != 200:
            return httpx.Response(status, headers={"location": "https://elsewhere.example/"})
        name = req.url.params["name"]
        answers = [{"name": name, "type": 16, "TTL": 300, "data": f'"{t}"'} for t in records.get(name, [])]
        return httpx.Response(200, json={"Status": 0, "Answer": answers}, headers={"content-type": "application/dns-json"})
    return httpx.MockTransport(handler)


def test_doh_request_shape_and_findings(tmp_path):
    calls, store = [], EvidenceStore(tmp_path / "e.db")
    transport = fake_doh({"shop.example": ["google-site-verification=abc"],
                          "_dmarc.shop.example": ["v=DMARC1; p=reject"]}, calls)
    [spf] = run_dns_check("missing_spf", "shop.example", VERIFIED, transport, store)
    assert run_dns_check("missing_dmarc", "shop.example", VERIFIED, transport, store) == []
    req = calls[0]
    assert req.method == "GET" and str(req.url).startswith(DOH_URL)
    assert req.headers["accept"] == "application/dns-json"
    assert dict(req.url.params) == {"name": "shop.example", "type": "TXT"}
    assert [c.url.params["name"] for c in calls] == ["shop.example", "_dmarc.shop.example"]
    assert spf.id == "missing_spf:TXT shop.example" and spf.severity == TABLE["missing_spf"].severity
    record = store.get(spf.evidence[0].record_id)  # the raw DoH answer is the evidence
    assert "google-site-verification=abc" in record["response"]["body"] and store.verify(record["id"])
    out = verify([{"finding_id": spf.id, "claim_type": "dns_record_missing"}], {spf.id: spf}, store)
    assert out["verified"][0]["supporting_evidence"].startswith("TXT shop.example:")


