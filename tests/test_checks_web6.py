def test_tls_thresholds_unit():
    now = datetime(2026, 10, 28, tzinfo=timezone.utc)
    info = {"host": "shop.example", "port": 443, "protocol": "TLSv1.3", "issuer": "CN=x"}
    checks = lambda d, p="TLSv1.3": [f.check for f in tls_findings(  # noqa: E731
        {**info, "protocol": p, "not_after": (now + timedelta(days=d)).isoformat()}, now)]
    assert checks(-3) == ["cert_expires_within_14_days"]  # already expired: still the high finding
    assert checks(13.9) == ["cert_expires_within_14_days"] and checks(14) == ["cert_expires_within_30_days"]
    assert checks(29.9) == ["cert_expires_within_30_days"] and checks(30) == []
    assert checks(90, "TLSv1") == ["tls_protocol_below_1_2"] and checks(90, "TLSv1.2") == []
    [f] = tls_findings({**info, "not_after": (now + timedelta(days=5)).isoformat()}, now)
    assert f.id == "cert_expires_within_14_days:tls://shop.example:443"


# --- web: which checks ran vs "not applicable for this target" ---

def test_web_result_lists_checks_ran_and_not_applicable(tmp_path):
    import time

    from src.web.server import make_server
    token, doh_calls = ["none"], []

    def handler(req):
        if req.url.host == "cloudflare-dns.com":
            doh_calls.append(req.url.params["name"])
            return httpx.Response(200, json={"Status": 0, "Answer": []})
        if req.url.host == "shop.example" and req.url.path == "/":
            return httpx.Response(200, headers={"content-type": "text/html"},
                                  text=f'<meta name="maya-verify" content="{token[0]}">'
                                       '<script src="/js/jquery-1.12.4.min.js"></script>')
        return httpx.Response(404, text="nope")

    server = make_server(port=0, data_dir=tmp_path, http_transport=httpx.MockTransport(handler),
                         provider_factory=lambda: (None, "none"))
    threading.Thread(target=server.serve_forever, daemon=True).start()
    c = httpx.Client(base_url=f"http://127.0.0.1:{server.server_address[1]}", trust_env=False, timeout=60)

    def post(path, body=None):
        return c.post(path, json=body or {}, headers={"X-CSRF-Token": c.get("/api/session").json()["csrf"]})

    def finished(asset_id):
        run_id = post(f"/api/assets/{asset_id}/scan").json()["run"]["id"]
        for _ in range(300):
            body = c.get(f"/api/runs/{run_id}").json()
            if body["run"]["status"] != "running":
                return body
            time.sleep(0.1)
        raise AssertionError("scan did not finish")

    try:
        assert post("/api/signup", {"email": "dns@shop.example", "password": "correct-horse-battery"}).status_code == 200
        for path, body in [("/api/profile", {"account_type": "company"}), ("/api/asset", {"asset": "website"}),
                           ("/api/connect", {"connect": True}), ("/api/consent", {"allow": True})]:
            assert post(path, body).status_code == 200
        demo = post("/api/assets", {"demo": True}).json()["asset"]
        checks = {x["check"]: x["status"] for x in finished(demo["id"])["result"]["checks"]}
        assert checks["missing_spf"] == checks["missing_dmarc"] == checks["weak_tls_or_expiring_cert"] == \
            "not applicable (loopback demo)"
        assert checks["outdated_js_library"] == checks["missing_csp"] == "ran"
        assert doh_calls == []  # nothing about the demo app ever goes to the DNS resolver

        site = post("/api/assets", {"url": "http://shop.example"}).json()["asset"]
        token[0] = site["verification"]["token"]
        assert post(f"/api/assets/{site['id']}/verify").json()["asset"]["status"] == "verified"
        body = finished(site["id"])
        checks = {x["check"]: x["status"] for x in body["result"]["checks"]}
        assert checks["missing_spf"] == checks["missing_dmarc"] == "ran"
        assert checks["weak_tls_or_expiring_cert"] == "not applicable (target is not HTTPS)"
        assert sorted(doh_calls) == ["_dmarc.shop.example", "shop.example"]
        ids = {f["id"] for f in body["result"]["findings"]}
        assert {"missing_spf:TXT shop.example", "missing_dmarc:TXT _dmarc.shop.example",
                "outdated_js_library:/:jquery"} <= ids
        sev = {f["id"]: f["severity"] for f in body["result"]["findings"]}
        assert sev["missing_spf:TXT shop.example"] == TABLE["missing_spf"].severity
    finally:
        c.close()
        server.shutdown()
        server.server_close()


