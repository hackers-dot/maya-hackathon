"""Developer export: one GitHub-issue-style markdown block per finding, from MAYA's fixed templates.

Everything that comes from a scan (location, target, evidence line, ids) goes inside code spans or fenced
code blocks whose fence is longer than any backtick run in the text, so it cannot break the markdown,
create links or @-mention anyone. Evidence lines are the stored, already-masked lines.
"""
import re

from src.fixes import PLANS
from src.report import TEXT, owasp_label

ACCEPTANCE = "MAYA re-test of this check shows FIXED"


def code_span(s) -> str:
    s = str(s).replace("\r", " ").replace("\n", " ")
    fence = "`" * (max((len(m) for m in re.findall(r"`+", s)), default=0) + 1)
    pad = " " if s.startswith("`") or s.endswith("`") or not s else ""
    return f"{fence}{pad}{s}{pad}{fence}"


def code_block(s, lang: str = "") -> str:
    s = str(s).replace("\r", "")
    fence = "`" * max(3, max((len(m) for m in re.findall(r"`+", s)), default=0) + 1)
    return f"{fence}{lang}\n{s}\n{fence}"


def one_line(s) -> str:
    return " ".join(str(s).split())


def issue(f: dict, target: str) -> dict:
    """f: a finding view (id, check, severity, location, title, evidence_line, plain, fix, owasp)."""
    t, plan = TEXT[f["check"]], PLANS.get(f["check"])
    title = one_line(f"[{f['severity'].upper()}] {t.title} ({f['location']})")[:250]
    parts = [
        f"**Severity:** {code_span(f['severity'])} (MAYA's fixed severity table)",
        f"**Check:** {code_span(f['check'])}",
        f"**Location:** {code_span(f['location'])} on {code_span(target)}",
        f"**Finding id:** {code_span(f['id'])}",
        f"**Category:** {owasp_label(f['check'])}",
        "", "### Evidence (masked where secret)", code_block(f.get("evidence_line") or "(none)"),
        "", "### What this means", t.plain,
        "", "### Fix", t.fix,
    ]
    if plan:
        parts += ["", "**nginx**", code_block(plan.nginx, "nginx"), "", "**Apache**", code_block(plan.apache, "apache"),
                  "", f"**Python / app code:** {plan.python_note}", "", f"**Risk of the change:** {plan.risk}",
                  "", "### Rollback", plan.rollback]
    parts += ["", "### Acceptance criterion", f"- [ ] {ACCEPTANCE} (check {code_span(f['check'])} at "
              f"{code_span(f['location'])}).", "", "_Generated by MAYA from fixed templates; proposed, not applied._"]
    return {"id": f["id"], "title": title, "body": "\n".join(parts)}


def issues_md(run_id: str, findings: list[dict], target: str) -> str:
    out = [f"# MAYA issues for run {code_span(run_id)}", "",
           f"{len(findings)} finding(s) on {code_span(target)}. One section per issue: copy the title and body.", ""]
    for f in findings:
        i = issue(f, target)
        out += ["---", "", f"## {i['title']}", "", i["body"], ""]
    return "\n".join(out)
